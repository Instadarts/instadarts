#!/usr/bin/env node
// Scan a client dist directory, compress all assets into a single Base64 gzipped payload,
// and write out a TypeScript module that exports EMBEDDED_CLIENT_BUNDLE.
//
//   node scripts/bundle-client.mjs <dist/client> <src/server/embeddedAssetsBundle.ts>

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { gzipSync } from 'node:zlib';

const [inputDirArg, outputFileArg] = process.argv.slice(2);

if (!inputDirArg || !outputFileArg) {
  console.error('Usage: node scripts/bundle-client.mjs <inputDir> <outputFile>');
  process.exit(1);
}

const inputDir = resolve(inputDirArg);
const outputFile = resolve(outputFileArg);

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...walk(fullPath));
    } else if (entry.isFile()) {
      files.push(fullPath);
    }
  }
  return files;
}

const allFiles = walk(inputDir);
if (allFiles.length === 0) {
  console.error(`Error: No files found in ${inputDir}`);
  process.exit(1);
}

const assetMap = {};
let totalUncompressedBytes = 0;

for (const filePath of allFiles) {
  const relPath = '/' + relative(inputDir, filePath).replace(/\\/g, '/');
  const buffer = readFileSync(filePath);
  totalUncompressedBytes += buffer.length;
  assetMap[relPath] = buffer.toString('base64');
}

const json = JSON.stringify(assetMap);
const compressed = gzipSync(Buffer.from(json, 'utf-8'), { level: 9 });
const base64Bundle = compressed.toString('base64');

const outputContent = `// Auto-generated by scripts/bundle-client.mjs - DO NOT EDIT MANUALLY
export const EMBEDDED_CLIENT_BUNDLE: string | null = ${JSON.stringify(base64Bundle)};
`;

writeFileSync(outputFile, outputContent, 'utf-8');

const uncompressedMB = (totalUncompressedBytes / 1024 / 1024).toFixed(2);
const compressedMB = (compressed.length / 1024 / 1024).toFixed(2);
console.log(`Bundled ${allFiles.length} client assets: ${uncompressedMB} MB raw -> ${compressedMB} MB compressed.`);
